export function getUIText(key, lang = 'nl') {
  const item = UI_TRANSLATIONS[key];
  if (!item) return key;
  return item[lang] || item['nl'] || item['en'] || key;
}

/**
 * Returns the UI label mainly in Dutch with the active mother tongue alongside it.
 * Example: "Spreek uit (انطق)" or "Volgende (التالي)"
 */
export function getDualUIText(key, lang = 'nl') {
  const item = UI_TRANSLATIONS[key];
  if (!item) return key;
  const nlText = item.nl || key;
  if (!lang || lang === 'nl') return nlText;
  const nativeText = item[lang];
  if (!nativeText || nativeText.toLowerCase().trim() === nlText.toLowerCase().trim()) {
    return nlText;
  }
  return `${nlText} (${nativeText})`;
}
